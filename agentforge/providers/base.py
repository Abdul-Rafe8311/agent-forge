"""Provider protocol; optional SDKs are absent from this module."""

from typing import Protocol

from ..types import ProviderCapabilities, ProviderRequest, ProviderResponse


class ModelProvider(Protocol):
    def generate(self, request: ProviderRequest) -> ProviderResponse: ...
    def count_input_tokens(self, request: ProviderRequest) -> int | None: ...
    def supports_strict_budget(self, request: ProviderRequest) -> bool: ...
    def capabilities(self, model: str) -> ProviderCapabilities: ...
    def close(self) -> None: ...
